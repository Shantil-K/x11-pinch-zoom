#!/usr/bin/python3
"""
Native messaging host for the Multi-touch Zoom extension (Linux / X11).

Listens to the Touchégg daemon's gesture broadcasts on D-Bus and forwards
touchpad pinch gestures to the extension as continuous scale values, so the
page zoom follows your fingers. The Touchégg daemon already reads the touchpad
as root, so this needs no extra permissions.

Messages sent to the extension: {"t": "begin" | "update" | "end", "s": <scale>}
where s is the pinch scale relative to the start of the gesture (1.0 = no change).
"""
import json
import os
import re
import shutil
import struct
import sys

import gi

gi.require_version('Gio', '2.0')
from gi.repository import Gio, GLib  # noqa: E402

TOUCHEGG_ADDRESS = 'unix:abstract=touchegg'
GESTURE_PINCH = 2
DIRECTION_IN = 5
DIRECTION_OUT = 6
DEVICE_TOUCHPAD = 1

CONFIG_DIR = os.path.expanduser('~/.config/multitouch-zoom')
METHOD_FILE = os.path.join(CONFIG_DIR, 'method')
KEYS_CONF = os.path.join(CONFIG_DIR, 'touchegg-keys.conf')  # used by switch-method.sh keys
TOUCHEGG_CONF = os.path.expanduser('~/.config/touchegg/touchegg.conf')

KEYSYM = re.compile(r'^[A-Za-z0-9_]{1,32}$')
MODIFIERS = {'Control_L', 'Alt_L', 'Shift_L', 'Super_L'}

TOUCHEGG_TEMPLATE = """<touchégg>

  <settings>
    <property name="animation_delay">150</property>
    <property name="action_execute_threshold">10</property>
    <property name="color">auto</property>
    <property name="borderColor">auto</property>
  </settings>

  <!-- Generated by Multi-touch Zoom from the shortcuts set in the extension popup -->
  <application name="Opera,opera,Google-chrome,google-chrome,Chromium,chromium,Brave-browser">
    <gesture type="PINCH" fingers="2" direction="OUT">
      <action type="SEND_KEYS">
        <repeat>true</repeat>
        <modifiers>{in_mods}</modifiers>
        <keys>{in_key}</keys>{decrease_out}
      </action>
    </gesture>

    <gesture type="PINCH" fingers="2" direction="IN">
      <action type="SEND_KEYS">
        <repeat>true</repeat>
        <modifiers>{out_mods}</modifiers>
        <keys>{out_key}</keys>{decrease_in}
      </action>
    </gesture>
  </application>

</touchégg>
"""


def valid_mods(mods):
    parts = mods.split('+') if mods else []
    return len(parts) > 0 and all(p in MODIFIERS for p in parts)


def write_keys_conf(in_mods, in_key, out_mods, out_key):
    """Write the Touchégg key-method config. Returns True if it's the active method."""
    if not (valid_mods(in_mods) and valid_mods(out_mods) and KEYSYM.match(in_key) and KEYSYM.match(out_key)):
        raise ValueError('invalid shortcut')
    os.makedirs(CONFIG_DIR, exist_ok=True)
    # Touchégg's decreaseKeys (reversing mid-pinch) reuses the same modifiers, so it's
    # only possible when both shortcuts share them
    same = in_mods == out_mods
    dec = '\n        <decreaseKeys>{}</decreaseKeys>'
    conf = TOUCHEGG_TEMPLATE.format(in_mods=in_mods, in_key=in_key, out_mods=out_mods, out_key=out_key,
                                    decrease_out=dec.format(out_key) if same else '',
                                    decrease_in=dec.format(in_key) if same else '')
    tmp = KEYS_CONF + '.tmp'
    with open(tmp, 'w') as f:
        f.write(conf)
    os.replace(tmp, KEYS_CONF)
    active = not helper_enabled_file_says_native()
    if active:
        os.makedirs(os.path.dirname(TOUCHEGG_CONF), exist_ok=True)
        shutil.copyfile(KEYS_CONF, TOUCHEGG_CONF)  # Touchégg reloads it automatically
    return active


def helper_enabled_file_says_native():
    try:
        with open(METHOD_FILE) as f:
            return f.read().strip() != 'keys'
    except OSError:
        return True


out = sys.stdout.buffer
connection = None
gesture_active = False


def helper_enabled():
    # switch-method.sh writes "keys" here when the Touchégg key method is in use
    return helper_enabled_file_says_native()


def send(msg):
    data = json.dumps(msg, separators=(',', ':')).encode()
    try:
        out.write(struct.pack('=I', len(data)) + data)
        out.flush()
    except BrokenPipeError:
        loop.quit()


def scale_from(direction, percentage):
    # Touchégg reports how far the pinch has moved, as a percentage, plus a direction
    p = percentage / 100.0
    if direction == DIRECTION_OUT:
        return 1.0 + p
    if direction == DIRECTION_IN:
        return max(1.0 - p, 0.05)
    return 1.0


def on_signal(_conn, _sender, _path, _iface, signal, params):
    gesture_type, direction, percentage, fingers, device, _elapsed = params.unpack()
    if gesture_type != GESTURE_PINCH or fingers != 2 or device != DEVICE_TOUCHPAD:
        return
    global gesture_active
    kind = {'OnGestureBegin': 'begin', 'OnGestureUpdate': 'update', 'OnGestureEnd': 'end'}.get(signal)
    if kind == 'begin':
        gesture_active = helper_enabled()  # checked once per gesture
    if kind and gesture_active:
        send({'t': kind, 's': round(scale_from(direction, percentage), 5)})


def on_closed(*_args):
    # Daemon restarted or went away: try to reconnect
    GLib.timeout_add_seconds(2, connect)


def connect():
    global connection
    try:
        connection = Gio.DBusConnection.new_for_address_sync(
            TOUCHEGG_ADDRESS, Gio.DBusConnectionFlags.AUTHENTICATION_CLIENT, None, None)
    except GLib.Error as e:
        send({'t': 'error', 'msg': f'cannot reach Touchégg daemon: {e.message}'})
        GLib.timeout_add_seconds(5, connect)
        return False
    connection.signal_subscribe(None, None, None, None, None, Gio.DBusSignalFlags.NONE, on_signal)
    connection.connect('closed', on_closed)
    send({'t': 'ready'})
    return False


inbuf = b''


def on_extension_message(msg):
    if msg.get('t') == 'setKeys':
        try:
            k_in, k_out = msg['in'], msg['out']
            active = write_keys_conf(k_in['mods'], k_in['key'], k_out['mods'], k_out['key'])
            send({'t': 'keysSaved', 'active': active})
        except (KeyError, TypeError, ValueError, OSError) as e:
            send({'t': 'keysError', 'msg': str(e)})


def on_stdin(_fd, condition):
    # The browser closes stdin when the extension disconnects; exit then.
    global inbuf
    chunk = os.read(sys.stdin.fileno(), 65536) if condition & GLib.IO_IN else b''
    if not chunk:
        loop.quit()
        return False
    inbuf += chunk
    while len(inbuf) >= 4:
        n = struct.unpack('=I', inbuf[:4])[0]
        if len(inbuf) < 4 + n:
            break
        raw, inbuf = inbuf[4:4 + n], inbuf[4 + n:]
        try:
            on_extension_message(json.loads(raw))
        except json.JSONDecodeError:
            pass
    return True


if len(sys.argv) == 6 and sys.argv[1] == '--write-keys-conf':
    # Used by switch-method.sh: pinch_host.py --write-keys-conf IN_MODS IN_KEY OUT_MODS OUT_KEY
    try:
        write_keys_conf(*sys.argv[2:6])
    except ValueError:
        sys.exit('invalid shortcut; modifiers are Control_L, Alt_L, Shift_L, Super_L joined by +')
    sys.exit(0)

loop = GLib.MainLoop()
GLib.io_add_watch(sys.stdin.fileno(), GLib.IO_IN | GLib.IO_HUP | GLib.IO_ERR, on_stdin)
connect()
loop.run()
